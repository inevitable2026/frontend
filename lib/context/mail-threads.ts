/**
 * 메일함 목업.
 *
 * 회사 메일함 커넥터는 아직 붙어 있지 않다. 화면이 "메일이 들어오면 이렇게 보인다" 를
 * 먼저 보여줘야 해서, 시나리오(docs/scenario-gimpo-logistics.md)에 적힌 메일과 같은
 * 내용을 여기에 고정 데이터로 둔다. 실제 커넥터가 붙으면 이 파일을 지우고
 * app/api/context/mail/route.ts 가 메일 서버를 읽도록 바꾸면 된다.
 *
 * 문서함(documents 테이블)과 달리 DB 에 넣지 않는 이유는, 사람이 만든 고정 데이터가
 * 실제 적재분과 같은 자리에 섞이면 어느 쪽이 사실인지 화면에서 구분할 수 없기 때문이다.
 */

/** 첨부가 문서함 적재 파이프라인의 어디까지 갔는지를 나타낸다. */
export type MailAttachmentState = "적재됨" | "적재대기" | "제외";

export type MailAttachment = {
  id: string;
  이름: string;
  쪽수: number;
  종류: DocumentKind;
  상태: MailAttachmentState;
  /** 적재된 첨부만 문서함의 행을 가리킨다. 목업이라 실제 uuid 는 아직 없다. */
  documentId: string | null;
};

export type MailMessage = {
  id: string;
  보낸시각: string;
  발신자: { 이름: string; 주소: string };
  수신: string[];
  참조: string[];
  본문: string;
  첨부: MailAttachment[];
};

/** 스레드를 맥락 베이스가 어디까지 처리했는지를 나타낸다. */
export type MailThreadState = "맥락 반영됨" | "검토 대기" | "보류";

export type MailThread = {
  id: string;
  /** public.sites.code 와 맞춘다. uuid 는 배포마다 달라지므로 코드로 묶는다. */
  siteCode: string;
  siteName: string;
  제목: string;
  상태: MailThreadState;
  라벨: string[];
  안읽음: boolean;
  마지막수신: string;
  참여자: string[];
  messages: MailMessage[];
  /** 스레드에서 읽어낸 값. 문서함의 extracted 와 같은 모양으로 맞춘다. */
  추출: ExtractedFields | null;
  /** 이 스레드를 왜 그 상태로 두었는지 한 줄로 남긴다. */
  판정메모: string;
};


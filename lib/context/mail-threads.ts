/** 현장 코드와 검색어로 스레드를 고른다. 최근 수신 순으로 돌려준다. */
export function selectMailThreads(filter: { siteCode?: string | null; q?: string | null } = {}): MailThread[] {
  const q = filter.q?.trim().toLowerCase();
  return MAIL_THREADS.filter((thread) => {
    if (filter.siteCode && thread.siteCode !== filter.siteCode) return false;
    if (!q) return true;
    const haystack = [
      thread.제목,
      thread.참여자.join(" "),
      ...thread.messages.map((m) => `${m.발신자.이름} ${m.본문}`),
    ]
      .join(" ")
      .toLowerCase();
    return haystack.includes(q);
  }).sort((a, b) => b.마지막수신.localeCompare(a.마지막수신));
}

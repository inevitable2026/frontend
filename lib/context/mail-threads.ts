import type { DocumentKind, ExtractedFields } from "@/lib/context/types";

/**
 * 메일함 목업.
 *
 * 회사 메일함 커넥터는 아직 붙어 있지 않다. 화면이 "메일이 들어오면 이렇게 보인다" 를
 * 먼저 보여줘야 해서, 시나리오(docs/scenario-gimpo-logistics.md)에 적힌 메일과 같은
 * 내용을 여기에 고정 데이터로 둔다. 실제 커넥터가 붙으면 이 파일을 지우고
 * app/api/context/mail/route.ts 가 메일 서버를 읽도록 바꾸면 된다.
 *
 * 문서함(documents 테이블)과 달리 DB 에 넣지 않는 이유는, 사람이 만든 고정 데이터가
 * 실제 적재분과 같은 자리에 섞이면 어느 쪽이 사실인지 화면에서 구분할 수 없기 때문이다.
 */

/**
 * 첨부가 문서함 적재 파이프라인의 어디까지 갔는지를 나타낸다.
 *
 * 값은 저장·비교에 쓰이므로 그대로 두고, 화면에 적을 말은 `첨부상태표시` 가 정한다.
 */
export type MailAttachmentState = "적재됨" | "적재대기" | "제외";

/**
 * 첨부 상태 → 화면에 적을 이름.
 *
 * 세 상태의 뜻이 서로 다르므로 합치지 않는다. `적재대기` 는 아직 저장 전이고,
 * `제외` 는 저장하지 않기로 한 것이다.
 */
export const 첨부상태표시: Record<MailAttachmentState, string> = {
  적재됨: "저장됨",
  적재대기: "저장 대기",
  제외: "저장 제외",
};

/**
 * 첨부를 눌렀을 때 띄우는 미리보기 한 쪽.
 *
 * 메일함이 목업이라 첨부에 대응하는 PDF 파일 자체가 없다. 그렇다고 눌러도 아무 반응이
 * 없게 두면 화면이 고장난 것으로 보이므로, 쪽마다 어떤 내용이 적혀 있는지를 글로 둔다.
 * 커넥터가 붙어 실제 파일이 생기면 이 필드를 지우고 화면이 파일을 그대로 띄우면 된다.
 *
 * 쪽수만큼 다 채우지는 않는다. 채운 쪽만 넣고, 화면에서 "전체 몇 쪽 가운데 몇 쪽" 인지를
 * 밝혀 목업임을 숨기지 않는다.
 */
export type MailAttachmentPage = {
  쪽: number;
  제목: string;
  문단: string[];
  /** 견적 항목이나 제원처럼 표로 적힌 줄. 없으면 빈 배열로 둔다. */
  표: Array<{ 항목: string; 값: string }>;
};

export type MailAttachment = {
  id: string;
  이름: string;
  쪽수: number;
  종류: DocumentKind;
  상태: MailAttachmentState;
  /** 적재된 첨부만 문서함의 행을 가리킨다. 목업이라 실제 uuid 는 아직 없다. */
  documentId: string | null;
  /** 원본 파일 대신 화면에 다시 그려 보여줄 내용. 채워 둔 쪽만 들어 있다. */
  미리보기: MailAttachmentPage[];
};

export type MailMessage = {
  id: string;
  보낸시각: string;
  발신자: { 이름: string; 주소: string };
  수신: string[];
  참조: string[];
  본문: string;
  첨부: MailAttachment[];
};

/**
 * 메일 묶음을 어디까지 처리했는지를 나타낸다.
 *
 * 값은 저장·비교에 쓰이므로 그대로 두고, 화면에 적을 말은 `묶음상태표시` 가 정한다.
 */
export type MailThreadState = "맥락 반영됨" | "검토 대기" | "보류";

/**
 * 메일 묶음 상태 → 화면에 적을 이름.
 *
 * `맥락 반영됨` 은 무엇이 어디에 반영됐는지가 드러나지 않아, 화면에서는 현장 자료에
 * 들어갔다는 뜻을 밝힌다. `검토 대기` 와 `보류` 는 뜻이 다르므로 합치지 않는다.
 */
export const 묶음상태표시: Record<MailThreadState, string> = {
  "맥락 반영됨": "현장 자료에 반영됨",
  "검토 대기": "검토 대기",
  보류: "보류",
};

export type MailThread = {
  id: string;
  /** public.sites.code 와 맞춘다. uuid 는 배포마다 달라지므로 코드로 묶는다. */
  siteCode: string;
  siteName: string;
  제목: string;
  상태: MailThreadState;
  라벨: string[];
  안읽음: boolean;
  마지막수신: string;
  참여자: string[];
  messages: MailMessage[];
  /** 스레드에서 읽어낸 값. 문서함의 extracted 와 같은 모양으로 맞춘다. */
  추출: ExtractedFields | null;
  /** 이 스레드를 왜 그 상태로 두었는지 한 줄로 남긴다. */
  판정메모: string;
};


/**
 * 어휘 값 합치기.
 *
 * 문서를 올릴 때마다 뽑힌 공종·장비·자재를 기존 선택에 **합집합**으로 얹는다. 합집합인
 * 이유는 사용자가 지운 것을 되살리지 않기 위해서다 — 그 판단은 그대로 둔다.
 *
 * 문제는 `new Set` 이 **글자가 똑같을 때만** 같다고 본다는 것이었다. 문서마다 표기가
 * 달라서 실제로 이런 것들이 나란히 쌓였다:
 *
 *     굴착기 · 굴착기 (백호)
 *     토공사 · 굴착작업
 *
 * 앞의 둘은 같은 장비다. 그대로 두면 평가표에 같은 기계가 두 줄로 들어가고, 화면에서는
 * "왜 다 선택돼 있지" 로 보인다. 여기서 표기 차이를 접는다.
 */

/**
 * 비교용 형태. 괄호 안 한정어와 띄어쓰기·구분기호를 걷어 낸다.
 *
 * 뜻까지 맞추려 들지 않는다. "토공사"와 "굴착작업"은 여기서 다른 값이고, 그게 맞다 —
 * 하나는 공종이고 하나는 그 안의 작업이라 사람이 판단할 몫이다. 이 함수가 접는 것은
 * **같은 것을 다르게 적은 경우**뿐이다.
 */
export function 비교형(값: string): string {
  return 값
    .replace(/\([^)]*\)/g, "")
    .replace(/[\s·∙・/,\-–—]/g, "")
    .toLowerCase();
}

/**
 * 기존 값에 새 값을 합친다.
 *
 * **이미 있는 값은 절대 바꾸지 않는다.** 새로 들어온 값이 기존 것과 표기만 다르면
 * 그냥 버린다. 처음에는 "더 구체적인 쪽(글자가 긴 쪽)을 남긴다"로 했는데, 그러면
 * 사용자가 직접 고른 "굴착기" 가 문서에서 들어온 "굴착기 (백호)" 로 **말없이
 * 바뀐다.** 화면에서 보면 자기가 고른 항목이 사라진 것이고, 되돌릴 방법도 없다.
 *
 * 그래서 접는 방향을 한쪽으로 고정한다 — 화면에 이미 있는 것이 이긴다. 더 구체적인
 * 이름이 필요하면 사용자가 직접 넣을 수 있다(피커가 임의 입력을 받는다).
 *
 * 기존 목록 안의 중복은 접지 않는다. 그건 사용자가 그렇게 만들어 둔 상태다.
 */
export function 합치기(기존: string[], 새것: readonly string[]): string[] {
  const 결과 = [...기존];
  const 자리 = new Set(기존.map(비교형).filter(Boolean));

  for (const 값 of 새것) {
    const v = 값.trim();
    if (!v) continue;
    const key = 비교형(v);
    if (!key || 자리.has(key)) continue;
    자리.add(key);
    결과.push(v);
  }

  return 결과;
}

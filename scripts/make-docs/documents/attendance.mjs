// ⑥ 출역 명부 — T-08 의 재료.
//
// 판정에는 두 종류의 문서가 함께 있어야 한다.
//   기준 집계 (2026-07-15 ~ 2026-08-13) — 직전 30일간의 출역 이력
//   일일 명부 4일치 (08-14 · 08-17 · 08-18 · 08-19) — 신규 11명이 여기서 처음 나타난다
// 기준 집계에 없는 personId 가 일일 명부에 있으면 그 인원이 신규다.

import { 문서, 머리표, 표, 서명란, esc, 체크, 강조행 } from "../lib/render.mjs";
import { 현장, 회사, 인물 } from "../data/site.mjs";
import {
  소속표,
  신규인원,
  일자목록,
  일일명부,
  업체별집계,
  기준기간,
  기준집계,
} from "../data/attendance.mjs";

const 개인표컬럼 = [
  { 제목: "연번", w: "6%", cls: "c" },
  { 제목: "성명", w: "14%" },
  { 제목: "생년", w: "8%", cls: "c" },
  { 제목: "소속", w: "26%" },
  { 제목: "직종", w: "12%", cls: "c" },
  { 제목: "최초 출역일", w: "12%", cls: "c" },
  { 제목: "신규", w: "6%", cls: "c" },
  { 제목: "출역 확인", w: "16%", cls: "c" },
];

function 기준문서() {
  const 집계 = 기준집계();
  return {
    id: "attendance-baseline",
    파일명: "07_출역이력_기준집계_20260715-20260813",
    kind: "기타",
    제목: "출역 이력 기준 집계표",
    먹이는조건: ["T-08"],
    html() {
      const 본문 = `
${머리표([
  [["현 장 명", 현장.name], ["문서번호", "GGC-01-ATT-BASE-202607"]],
  [["집계 기간", `${기준기간.시작} ~ ${기준기간.종료}`], ["가동 일수", `${기준기간.가동일수}일`]],
  [["집계 대상", "출입관리시스템 기록 기준 전 인원"], ["작성일", "2026-08-14"]],
  [["용    도", "신규 입장자 판정 기준 — 이 표에 없는 인원이 신규다."]],
])}

<h2>1. 업체별 연인원</h2>
${표(
  [
    { 제목: "업체", w: "34%" },
    { 제목: "구분", w: "22%", cls: "c" },
    { 제목: "등록 인원", w: "12%", cls: "c" },
    { 제목: "연인원", w: "14%", cls: "r" },
    { 제목: "평균 출역일", w: "18%", cls: "c" },
  ],
  소속표.map((s) => {
    const 인원 = 집계.filter((p) => p.소속key === s.key);
    const 연인원 = 인원.reduce((a, p) => a + p.출역일수, 0);
    return [
      esc(s.회사),
      esc(s.구분),
      `${인원.length}명`,
      연인원.toLocaleString(),
      `${(연인원 / 인원.length).toFixed(1)}일`,
    ];
  }),
)}

<h2>2. 개인별 출역일수 (${집계.length}명)</h2>
${표(
  [
    { 제목: "연번", w: "6%", cls: "c" },
    { 제목: "성명", w: "14%" },
    { 제목: "생년", w: "9%", cls: "c" },
    { 제목: "소속", w: "31%" },
    { 제목: "직종", w: "14%", cls: "c" },
    { 제목: "최초 출역일", w: "13%", cls: "c" },
    { 제목: "출역일수", w: "13%", cls: "c" },
  ],
  집계.map((p, i) => [
    String(i + 1),
    esc(p.성명),
    String(p.생년),
    esc(p.소속),
    esc(p.직종),
    esc(p.최초출역일),
    `${p.출역일수} / ${기준기간.가동일수}`,
  ]),
)}

${서명란(
  [
    { 소속: 회사.원청, 직위: "작성", 성명: 인물.최민서.성명 },
    { 소속: 회사.원청, 직위: "확인", 성명: 인물.박정우.성명 },
    { 소속: 회사.원청, 직위: "승인", 성명: 인물.황인철.성명 },
  ],
  3,
  "작성 · 확인",
)}
`;
      return 문서({
        제목: "출역 이력 기준 집계표",
        문서번호: "GGC-01-ATT-BASE-202607",
        머리말: `${esc(회사.원청)} &nbsp;|&nbsp; ${esc(현장.name)}`,
        본문,
      });
    },
  };
}

function 일일문서(일자) {
  const 명부 = 일일명부(일자);
  const 집계 = 업체별집계(명부);
  const 통역 = 명부.신규.filter((p) => p.통역필요);
  const 번호 = `GGC-01-ATT-${일자.replace(/-/g, "")}`;

  return {
    id: `attendance-${일자.replace(/-/g, "")}`,
    파일명: `08_출역명부_${일자.replace(/-/g, "")}`,
    kind: "기타",
    제목: `출역 명부 ${일자}`,
    먹이는조건: ["T-08"],
    html() {
      const 본문 = `
${머리표([
  [["현 장 명", 현장.name], ["문서번호", 번호]],
  [["출역 일자", `${일자} (${명부.요일})`], ["작업 시간", "07:00 ~ 17:00"]],
  [["총 출역 인원", `<b>${명부.인원.length}명</b>`], ["결원", `${명부.결원수}명`]],
  [["금일 신규 입장자", `<b>${명부.신규.length}명</b>`], ["통역 필요 인원", `<b>${통역.length}명</b>`]],
])}

<h2>1. 업체별 출역 집계</h2>
${표(
  [
    { 제목: "업체", w: "30%" },
    { 제목: "구분", w: "20%", cls: "c" },
    { 제목: "배정", w: "10%", cls: "c" },
    { 제목: "출역", w: "10%", cls: "c" },
    { 제목: "신규", w: "10%", cls: "c" },
    { 제목: "통역 필요", w: "10%", cls: "c" },
    { 제목: "확인", w: "10%", cls: "c" },
  ],
  집계.map((r) => {
    const cells = [
      esc(r.회사),
      esc(r.구분),
      `${r.정원}명`,
      `${r.출역}명`,
      r.신규 > 0 ? `<b>${r.신규}명</b>` : "-",
      r.통역 > 0 ? `<b>${r.통역}명</b>` : "-",
      '<span class="blank sm"></span>',
    ];
    return r.신규 > 0 ? 강조행(cells) : cells;
  }),
)}

<h2>2. 금일 신규 입장자 (${명부.신규.length}명)</h2>
${
  명부.신규.length === 0
    ? '<p>해당 없음.</p>'
    : 표(
        [
          { 제목: "연번", w: "6%", cls: "c" },
          { 제목: "성명", w: "16%" },
          { 제목: "생년", w: "8%", cls: "c" },
          { 제목: "소속", w: "24%" },
          { 제목: "직종", w: "11%", cls: "c" },
          { 제목: "국적", w: "11%", cls: "c" },
          { 제목: "통역 필요", w: "8%", cls: "c" },
          { 제목: "신규교육 이수", w: "8%", cls: "c" },
          { 제목: "확인 서명", w: "8%", cls: "c" },
        ],
        명부.신규.map((p, i) => [
          String(i + 1),
          `<b>${esc(p.성명)}</b>`,
          String(p.생년),
          esc(p.소속),
          esc(p.직종),
          esc(p.국적),
          p.통역필요 ? '<b>필요</b>' : "-",
          '<span class="blank sm"></span>',
          '<span class="blank sm"></span>',
        ]),
      )
}
${
  통역.length > 0
    ? `<div class="note"><b>통역 필요</b> — ${통역
        .map((p) => `${esc(p.성명)}(${esc(p.국적)})`)
        .join(" · ")}. 신규 입장자 교육과 당일 TBM 전달 방안을 별도로 정해야 한다.</div>`
    : ""
}

<h2>3. 개인별 출역 명부 (${명부.인원.length}명)</h2>
${표(
  개인표컬럼,
  명부.인원.map((p) => {
    const cells = [
      String(p.연번),
      esc(p.성명),
      String(p.생년),
      esc(p.소속),
      esc(p.직종),
      esc(p.최초출역일),
      체크(p.신규 && p.최초출역일 === 일자),
      '<span class="blank" style="min-width:22mm"></span>',
    ];
    return p.최초출역일 === 일자 ? 강조행(cells) : cells;
  }),
)}
<div class="legend">「신규」란에 표시된 인원은 직전 30일간 출역 기록이 없는 인원이다. 기준은 GGC-01-ATT-BASE-202607 이다.</div>

${서명란(
  [
    { 소속: 회사.원청, 직위: "작성", 성명: 인물.최민서.성명 },
    { 소속: 회사.원청, 직위: "확인", 성명: 인물.박정우.성명 },
    { 소속: 회사.골조, 직위: "작업반장", 성명: 인물.이재훈.성명 },
    { 소속: 회사.가설, 직위: "반장", 성명: 인물.김성태.성명 },
  ],
  4,
  "작성 · 확인",
)}
`;
      return 문서({
        제목: "일일 출역 명부",
        문서번호: 번호,
        머리말: `${esc(회사.원청)} &nbsp;|&nbsp; ${esc(현장.name)} &nbsp;|&nbsp; ${esc(일자)} (${esc(명부.요일)})`,
        본문,
      });
    },
  };
}

export default [기준문서(), ...일자목록.map(일일문서)];

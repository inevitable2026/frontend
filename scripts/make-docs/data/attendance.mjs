/** 그날 결원(개인 사정·휴무). 결정론적으로 뽑는다. */
function 결원(일자) {
  const rnd = lcg(Number(일자.replace(/-/g, "")));
  const set = new Set();
  const 수 = 3 + Math.floor(rnd() * 5);
  while (set.size < 수) set.add(Math.floor(rnd() * 기존인원.length));
  return set;
}

/**
 * 그날의 출역 명부.
 * @returns {{일자:string, 요일:string, 인원:Array, 신규:Array, 결원수:number}}
 */
export function 일일명부(일자) {
  const 빠진 = 결원(일자);
  const 기존 = 기존인원.filter((_, i) => !빠진.has(i));
  const 이미들어온신규 = 신규인원.filter((p) => p.최초출역일 <= 일자);
  const 오늘신규 = 신규인원.filter((p) => p.최초출역일 === 일자);
  const 인원 = [...기존, ...이미들어온신규].map((p, i) => ({ ...p, 연번: i + 1 }));
  return { 일자, 요일: 요일[일자], 인원, 신규: 오늘신규, 결원수: 빠진.size };
}

/** 업체별 집계. */
export function 업체별집계(명부) {
  return 소속표.map((s) => {
    const 인원 = 명부.인원.filter((p) => p.소속key === s.key);
    const 신규 = 명부.신규.filter((p) => p.소속key === s.key);
    return {
      회사: s.회사,
      구분: s.구분,
      정원: s.정원 + 신규인원.filter((p) => p.소속key === s.key && p.최초출역일 <= 명부.일자).length,
      출역: 인원.length,
      신규: 신규.length,
      통역: 신규.filter((p) => p.통역필요).length,
    };
  });
}


import assert from "node:assert/strict";
import test from "node:test";

import { 비교형, 합치기 } from "../tmp/test-dist/lib/risk/vocab.js";

test("비교형은 괄호 한정어와 띄어쓰기·구분기호를 걷어 낸다", () => {
  assert.equal(비교형("굴착기 (백호)"), 비교형("굴착기"));
  assert.equal(비교형("콘크리트 작업"), 비교형("콘크리트작업"));
  assert.equal(비교형("사다리 / 가설통로"), "사다리가설통로");
});

test("비교형은 뜻까지 맞추려 들지 않는다", () => {
  // 하나는 공종이고 하나는 그 안의 작업이다. 현장이 둘 다 쓰므로 접으면 안 된다.
  assert.notEqual(비교형("토공사"), 비교형("굴착작업"));
});

test("합치기는 표기만 다른 값을 다시 쌓지 않는다", () => {
  // 문서마다 표기가 달라 "굴착기" 와 "굴착기 (백호)" 가 나란히 쌓이던 자리다.
  // 장비 14·자재 16 처럼 아무도 고르지 않은 것들이 골라진 채로 생성이 돌았다.
  assert.deepEqual(합치기(["굴착기"], ["굴착기 (백호)", "덤프트럭"]), ["굴착기", "덤프트럭"]);
});

test("합치기는 이미 있는 값을 절대 바꾸지 않는다", () => {
  // 처음에는 "더 구체적인 쪽(긴 쪽)을 남긴다" 로 했는데, 그러면 사용자가 직접 고른
  // "굴착기" 가 문서에서 들어온 "굴착기 (백호)" 로 말없이 바뀐다. 화면에서 보면
  // 자기가 고른 항목이 사라진 것이고 되돌릴 방법도 없다.
  const 기존 = ["굴착기"];
  assert.deepEqual(합치기(기존, ["굴착기 (백호)"]), ["굴착기"]);
  assert.deepEqual(기존, ["굴착기"], "원본 배열을 건드리지 않는다");
});

test("합치기는 기존 순서를 지키고 새 값을 뒤에 붙인다", () => {
  assert.deepEqual(합치기(["가", "나"], ["다", "가"]), ["가", "나", "다"]);
});

test("합치기는 빈 값과 공백만 있는 값을 버린다", () => {
  assert.deepEqual(합치기([], ["", "   ", "레미콘"]), ["레미콘"]);
});

test("합치기는 기존 목록 안의 중복은 접지 않는다", () => {
  // 그건 사용자가 그렇게 만들어 둔 상태다. 말없이 정리하면 또 항목이 사라진다.
  assert.deepEqual(합치기(["굴착기", "굴착기 (백호)"], []), ["굴착기", "굴착기 (백호)"]);
});
